// One-off importer: ../6 Live preview/data/products.json -> src/config/catalog.generated.js
import fs from 'node:fs'
const src = JSON.parse(fs.readFileSync(new URL('../../6 Live preview/data/products.json', import.meta.url), 'utf8'))
const slugify = s => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const cats = new Map()
const products = src.map(p => {
  const cslug = slugify(p.cat)
  if (!cats.has(cslug)) cats.set(cslug, { slug: cslug, name: p.cat, group: p.group, description: '', image: '/' + p.imgs[0].replace(/^img\//, 'products/'), count: 0 })
  cats.get(cslug).count++
  const compare = p.market && p.market > p.price * 1.015 ? Math.round(p.market) : undefined
  const off = p.offroad
  const short = `${p.brand} ${p.name.replace(new RegExp('^' + p.brand + '\s*', 'i'), '')} — ${p.cat.toLowerCase()} with Australia-wide delivery.`
  const legal = off
    ? ' Off-road / private property use only — not registrable or road legal in Australia.'
    : ' Check your state road authority rules before riding on public roads.'
  return {
    slug: p.slug, name: p.name, brand: p.brand, price: p.price,
    comparePrice: compare || 0,
    bestPrice: p.priceType === 'beat',
    category: cslug,
    shortDescription: short.length > 160 ? short.slice(0, 157) + '…' : short,
    description: `${p.name} from ${p.brand}, supplied by Torque E-Bikes in the ${p.cat} range.${legal} Specifications are those published by the manufacturer; contact us to confirm fitment, stock and delivery to your postcode.`,
    compliance: off ? 'off-road' : '',
    badge: '',
    power: 'N/A',
    voltage: 'N/A',
    compatibility: [],
    featured: false,
    images: p.imgs.map(i => '/' + i.replace(/^img\//, 'products/')),
    stock: 'In Stock',
  }
})
for (const c of cats.values()) c.description = `Shop ${c.count} ${c.name.toLowerCase()} from leading brands. Australia-wide shipping from Brisbane, with Class 9 DG certified battery freight.`
let nf=0;for(const q of products){const o=src.find(p=>p.slug===q.slug);if(nf<8&&o.cat==='Electric Dirt Bikes'&&o.source==='verified'&&q.bestPrice){q.featured=true;nf++}}
const out = `// AUTO-GENERATED by scripts/import-catalog.mjs — do not edit by hand\nexport const CATALOG_CATEGORIES = ${JSON.stringify([...cats.values()], null, 1)}\n\nexport const CATALOG_PRODUCTS = ${JSON.stringify(products)}\n`
fs.writeFileSync(new URL('../src/config/catalog.generated.js', import.meta.url), out)
console.log(products.length, 'products', cats.size, 'categories')
