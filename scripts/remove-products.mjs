// One-off (6 Nov 2026): removes the 115 owner-approved "REMOVE" products listed in docs/remove-keep-report-2026-11-06.csv.
// Each removed URL gets a permanent 301 (src/config/product-redirects.generated.json) to the nearest live page:
// a kept product of the same brand and category with the nearest price, otherwise the category page.
// Usage: node scripts/remove-products.mjs            (dry run, prints the plan)
//        node scripts/remove-products.mjs --apply    (writes the changes)
import fs from 'node:fs'
import cp from 'node:child_process'

const ROOT = process.cwd().replace(/\\/g, '/') + '/'
const APPLY = process.argv.includes('--apply')
const read = f => fs.readFileSync(ROOT + f, 'utf8')
const write = (f, s) => { if (APPLY) fs.writeFileSync(ROOT + f, s) }

const parseCsv = s => { const rows = []; let r = [], c = '', q = false; for (let i = 0; i < s.length; i++) { const ch = s[i]; if (q) { if (ch === '"') { if (s[i + 1] === '"') { c += '"'; i++ } else q = false } else c += ch } else if (ch === '"') q = true; else if (ch === ',') { r.push(c); c = '' } else if (ch === '\n' || ch === '\r') { if (ch === '\r' && s[i + 1] === '\n') i++; r.push(c); c = ''; if (r.length > 1 || r[0]) rows.push(r); r = [] } else c += ch } if (c || r.length) { r.push(c); rows.push(r) } return rows }
const rep = parseCsv(read('docs/remove-keep-report-2026-11-06.csv')); const H = rep.shift()
const RM = new Set(rep.map(r => Object.fromEntries(H.map((k, i) => [k, r[i]]))).filter(r => r.bucket === 'REMOVE').map(r => r.slug))
if (RM.size !== 115) throw new Error('expected 115 removals, got ' + RM.size)

const { CATALOG_PRODUCTS } = await import('file:///' + ROOT + 'src/config/catalog-products.generated.js')
const { CATALOG_CATEGORIES } = await import('file:///' + ROOT + 'src/config/catalog.generated.js')
const { MIN_BRAND_PRODUCTS, KEEP_BRANDS } = await import('file:///' + ROOT + 'src/config/brand-rules.js')
const slugify = s => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const gone = CATALOG_PRODUCTS.filter(p => RM.has(p.slug))
if (gone.length !== 115) throw new Error('catalogue match ' + gone.length)
const kept = CATALOG_PRODUCTS.filter(p => !RM.has(p.slug))
const urlOf = p => `/shop/${p.category}/${p.slug}/`

// ---- destinations
const dest = {}
for (const p of gone) {
  const sib = kept.filter(q => q.category === p.category && p.brand && p.brand !== 'TBC' && q.brand === p.brand).sort((a, b) => Math.abs(a.price - p.price) - Math.abs(b.price - p.price))[0]
  dest[urlOf(p)] = sib ? urlOf(sib) : `/shop/${p.category}/`
}

// ---- brand pages that fall below the threshold
const brandCount = list => { const m = {}; list.filter(p => p.brand && p.brand !== 'TBC').forEach(p => { const s = slugify(p.brand); m[s] = (m[s] || 0) + 1 }); return m }
const before = brandCount(CATALOG_PRODUCTS), after = brandCount(kept)
const hasPage = (m, s) => (m[s] || 0) >= MIN_BRAND_PRODUCTS || (KEEP_BRANDS.includes(s) && (m[s] || 0) > 0)
const newlyThin = Object.keys(before).filter(s => hasPage(before, s) && !hasPage(after, s))
const brandDest = {}
for (const s of newlyThin) {
  const items = kept.filter(p => p.brand && p.brand !== 'TBC' && slugify(p.brand) === s)
  if (items.length === 0) { const any = gone.find(p => p.brand && slugify(p.brand) === s); brandDest[`/brands/${s}/`] = `/shop/${any.category}/`; continue }
  const t = {}; items.forEach(p => { t[p.category] = (t[p.category] || 0) + 1 })
  const top = Object.keys(t).sort((a, b) => t[b] - t[a])[0]
  brandDest[`/brands/${s}/`] = items.length === 1 ? urlOf(items[0]) : `/shop/${top}/`
}
console.log('removing', gone.length, '| kept', kept.length, '| brand pages newly thin:', newlyThin.join(', '))

// ---- existing brand redirects that point at a removed product (the brand has no products left, so the generator would drop them)
const brandRedirects = JSON.parse(read('src/config/brand-redirects.generated.json'))
const orphanBrandRedirects = brandRedirects.filter(r => dest[r.destination]).map(r => ({ source: r.source, destination: dest[r.destination] }))

// ---- 1. catalogue and category counts
const cpFile = 'src/config/catalog-products.generated.js'
write(cpFile, '// AUTO-GENERATED by scripts/import-catalog.mjs — do not edit by hand\nexport const CATALOG_PRODUCTS = ' + JSON.stringify(kept) + '\n')
const catTxt = read('src/config/catalog.generated.js')
const cnt = {}; kept.forEach(p => { cnt[p.category] = (cnt[p.category] || 0) + 1 })
const cats = CATALOG_CATEGORIES.map(c => ({ ...c, count: cnt[c.slug] || 0, description: c.description.replace(/^Shop \d+ /, `Shop ${cnt[c.slug] || 0} `) }))
if (cats.some(c => !c.count)) throw new Error('a category would be empty')
write('src/config/catalog.generated.js', '// AUTO-GENERATED by scripts/import-catalog.mjs — do not edit by hand\nexport const CATALOG_CATEGORIES = ' + JSON.stringify(cats, null, 1) + '\n\n')

// ---- 2. redirects
const redirects = [...gone.map(p => ({ source: `/shop/${p.category}/${p.slug}`, destination: dest[urlOf(p)] })), ...orphanBrandRedirects]
write('src/config/product-redirects.generated.json', JSON.stringify(redirects, null, 1) + '\n')

// ---- 3. generated config keyed by page
const goneUrls = new Set(gone.map(urlOf))
const jf = (f, fn) => { const o = JSON.parse(read(f)); const n = fn(o); write(f, JSON.stringify(o)); return n }
const drop = (obj, keys) => { let n = 0; keys.forEach(k => { if (k in obj) { delete obj[k]; n++ } }); return n }
const brandUrls = newlyThin.map(s => `/brands/${s}/`)
const stats = {}
stats.seo = jf('src/config/seo.generated.json', o => drop(o, [...goneUrls, ...brandUrls]))
stats.faq = jf('src/config/faq.generated.json', o => drop(o.pages, [...goneUrls, ...brandUrls]))
stats.copy = jf('src/config/product-copy.generated.json', o => drop(o, [...RM]))
stats.noindex = jf('src/config/noindex-products.json', o => { const n = o.filter(s => RM.has(s)).length; o.splice(0, o.length, ...o.filter(s => !RM.has(s))); return n })
stats.gap = jf('src/config/gap-links.generated.json', o => { let n = drop(o, [...goneUrls]); Object.values(o).forEach(m => { n += drop(m, [...goneUrls]) }); return n })
write('src/config/merged-brand-pages.json', JSON.stringify([...new Set([...JSON.parse(read('src/config/merged-brand-pages.json')), ...newlyThin])].sort(), null, 1) + '\n')

// ---- 4. blog and page content: drop product cards and comparison-table rows, retarget every other link
const allDest = { ...dest, ...brandDest }
const files = cp.execSync('git ls-files src/content src/config/product-copy.generated.json', { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(f => f.endsWith('.js') || f.endsWith('.json'))
const urlRe = /(?:\/shop\/[a-z0-9-]+\/[a-z0-9-]+\/|\/brands\/[a-z0-9-]+\/)/g
const cardsLeft = {}
let cardsDropped = 0, rowsDropped = 0, retargeted = 0
for (const f of files) {
  const orig = read(f); let t = orig
  if (!orig.includes('/shop/') && !orig.includes('/brands/')) continue
  const lines = orig.split('\n'); const out = []
  for (const l of lines) {
    const m = l.match(/^\s*\{\s*href:\s*'(\/shop\/[^']+)'/)
    if (m && goneUrls.has(m[1])) { cardsDropped++; continue }
    if (/^\s*\['\[/.test(l)) { const u = (l.match(/\]\((\/shop\/[^)]+)\)/) || [])[1]; if (u && goneUrls.has(u)) { rowsDropped++; continue } }
    out.push(l)
  }
  t = out.join('\n')
  t = t.replace(urlRe, u => { if (allDest[u]) { retargeted++; return allDest[u] } return u })
  if (t !== orig) {
    write(f, t)
    if (f.startsWith('src/content/blog/') && !f.endsWith('meta.js') && !f.endsWith('bodies.js')) cardsLeft[f] = (t.match(/^\s*\{\s*href:\s*'\/shop\//gm) || []).length
  }
}
console.log('cards dropped', cardsDropped, '| table rows dropped', rowsDropped, '| links retargeted', retargeted)
const thinPosts = Object.entries(cardsLeft).filter(([, n]) => n < 2)
console.log('blog files with fewer than 2 product cards left:', thinPosts.length, thinPosts.map(([f, n]) => f.replace('src/content/blog/', '') + ':' + n).join(', '))

// ---- 5. docs
const csvRows = (f, urlCol) => {
  const rows = parseCsv(read(f)); const h = rows.shift(); const i = h.indexOf(urlCol)
  return { h, rows, i }
}
const q = v => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v)
{ // keyword register: release rows for removed pages (and for newly thin brand pages)
  const lines = read('docs/used-keywords.csv').split('\n'); let n = 0
  const keep = lines.filter(l => { const u = l.split(',')[0]; const hit = goneUrls.has(u) || brandUrls.includes(u); if (hit) n++; return !hit })
  write('docs/used-keywords.csv', keep.join('\n')); stats.register = n
}
{ // link plan: rows whose source or target page no longer exists
  const { h, rows } = csvRows('docs/link-plan.csv', 'target')
  const kept2 = rows.filter(r => !r.some(c => goneUrls.has(c) || brandUrls.includes(c)))
  stats.linkPlan = rows.length - kept2.length
  write('docs/link-plan.csv', [h, ...kept2].map(r => r.map(q).join(',')).join('\n') + '\n')
}
{ // thin-product list
  const rows = parseCsv(read('docs/thin-products.csv')); const h = rows.shift()
  const kept2 = rows.filter(r => !RM.has(r[0])); stats.thin = rows.length - kept2.length
  write('docs/thin-products.csv', [h, ...kept2].map(r => r.map(q).join(',')).join('\n') + '\n')
}
write('docs/removed-products-2026-11-06.csv', 'slug,name,brand,category,price,old_url,redirects_to\n' + gone.map(p => [p.slug, p.name, p.brand, p.category, p.price, urlOf(p), dest[urlOf(p)]].map(v => q(String(v))).join(',')).join('\n') + '\n')
console.log(stats, '| newly merged brand pages -> ', brandDest, '| orphan brand redirects re-pointed:', orphanBrandRedirects.length)
console.log(APPLY ? 'APPLIED' : 'DRY RUN (nothing written)')
