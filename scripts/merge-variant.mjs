// Merges a variant product page into its main product page with a permanent redirect.
// Usage: node scripts/merge-variant.mjs <variant-slug> <main-slug> [--apply]
import fs from 'node:fs'

const ROOT = process.cwd().replace(/\\/g, '/') + '/'
const APPLY = process.argv.includes('--apply')
const [VARIANT, MAIN] = process.argv.slice(2).filter(a => !a.startsWith('--'))
const NL = String.fromCharCode(10)
const read = f => fs.readFileSync(ROOT + f, 'utf8')
const write = (f, s) => { if (APPLY) fs.writeFileSync(ROOT + f, s) }

const cur = await import('file:///' + ROOT + 'src/config/catalog-products.generated.js')
const v = cur.CATALOG_PRODUCTS.find(p => p.slug === VARIANT)
const m = cur.CATALOG_PRODUCTS.find(p => p.slug === MAIN)
if (!v || !m) throw new Error('variant or main product not found')
const vUrl = `/shop/${v.category}/${v.slug}/`, mUrl = `/shop/${m.category}/${m.slug}/`
console.log('merging', vUrl, '->', mUrl)

const kept = cur.CATALOG_PRODUCTS.filter(p => p.slug !== VARIANT)
write('src/config/catalog-products.generated.js', '// AUTO-GENERATED by scripts/import-catalog.mjs — do not edit by hand' + NL + 'export const CATALOG_PRODUCTS = ' + JSON.stringify(kept) + NL)
const { CATALOG_CATEGORIES } = await import('file:///' + ROOT + 'src/config/catalog.generated.js')
const cnt = {}; kept.forEach(p => { cnt[p.category] = (cnt[p.category] || 0) + 1 })
write('src/config/catalog.generated.js', '// AUTO-GENERATED by scripts/import-catalog.mjs — do not edit by hand' + NL + 'export const CATALOG_CATEGORIES = ' + JSON.stringify(CATALOG_CATEGORIES.map(c => ({ ...c, count: cnt[c.slug] || 0, description: c.description.replace(/^Shop \d+ /, `Shop ${cnt[c.slug] || 0} `) })), null, 1) + NL + NL)

const jf = (f, fn) => { const o = JSON.parse(read(f)); fn(o); write(f, JSON.stringify(o)) }
jf('src/config/seo.generated.json', o => { delete o[vUrl] })
jf('src/config/faq.generated.json', o => { delete o.pages[vUrl] })
jf('src/config/product-copy.generated.json', o => { delete o[VARIANT] })
jf('src/config/gap-links.generated.json', o => { delete o[vUrl]; Object.values(o).forEach(x => { delete x[vUrl] }) })

const red = JSON.parse(read('src/config/product-redirects.generated.json'))
red.push({ source: `/shop/${v.category}/${v.slug}`, destination: mUrl })
write('src/config/product-redirects.generated.json', JSON.stringify(red, null, 1) + NL)

const reg = read('docs/used-keywords.csv').split(NL).filter(l => l.split(',')[0] !== vUrl)
write('docs/used-keywords.csv', reg.join(NL))
const lp = read('docs/link-plan.csv').split(NL).filter(l => !l.includes(vUrl))
write('docs/link-plan.csv', lp.join(NL))

// blog and page content: drop cards for the variant, retarget other links to the main page
const files = []
const walk = d => { for (const e of fs.readdirSync(ROOT + d, { withFileTypes: true })) { const p = d + '/' + e.name; if (e.isDirectory()) walk(p); else if (/\.(js|json)$/.test(e.name)) files.push(p) } }
walk('src/content'); files.push('src/config/product-copy.generated.json')
let n = 0
for (const f of files) {
  const t = read(f); if (!t.includes(vUrl)) continue
  const out = t.split(NL).filter(l => !(new RegExp("^\\s*\\{\\s*href:\\s*'" + vUrl.replace(/\//g, '\\/') + "'").test(l))).join(NL).split(vUrl).join(mUrl)
  if (out !== t) { write(f, out); n++ }
}
console.log('content files updated', n, APPLY ? 'APPLIED' : 'DRY RUN')
