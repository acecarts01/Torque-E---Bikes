// One-off (6 Nov 2026): restores products removed in ec59a2b after the Groups-view re-check showed the removal rested on a false "no data".
// Usage: node scripts/restore-products.mjs <slug> [<slug> ...]            (dry run)
//        node scripts/restore-products.mjs --apply <slug> [<slug> ...]
import fs from 'node:fs'
import cp from 'node:child_process'

const ROOT = process.cwd().replace(/\\/g, '/') + '/'
const APPLY = process.argv.includes('--apply')
const SLUGS = process.argv.slice(2).filter(a => !a.startsWith('--'))
const BASE = 'e3078c0' // last commit before the removal
const NL = String.fromCharCode(10)
const git = f => cp.execSync(`git show ${BASE}:${f}`, { cwd: ROOT, encoding: 'utf8', maxBuffer: 1e9 })
const read = f => fs.readFileSync(ROOT + f, 'utf8')
const write = (f, s) => { if (APPLY) fs.writeFileSync(ROOT + f, s) }

// real Semrush primaries found in the Groups-view check (replace the generated primary)
const REAL = { 'rerode-r1-electric-dirt-bike': ['rerode r1', 140, 6, 'Commercial'] }

const oldTxt = git('src/config/catalog-products.generated.js')
const OLD = JSON.parse(oldTxt.slice(oldTxt.indexOf('[')).trim())
const cur = await import('file:///' + ROOT + 'src/config/catalog-products.generated.js')
const curSlugs = new Set(cur.CATALOG_PRODUCTS.map(p => p.slug))
const want = new Set(SLUGS)
const missing = SLUGS.filter(s => !OLD.some(p => p.slug === s))
if (missing.length) throw new Error('not in the old catalogue: ' + missing)
const restored = OLD.filter(p => want.has(p.slug) && !curSlugs.has(p.slug))
const urlOf = p => `/shop/${p.category}/${p.slug}/`
const urls = new Set(restored.map(urlOf))
const merged = OLD.filter(p => curSlugs.has(p.slug) || want.has(p.slug))
console.log('restoring', restored.map(p => p.slug).join(', '), '| catalogue', cur.CATALOG_PRODUCTS.length, '->', merged.length)

write('src/config/catalog-products.generated.js', '// AUTO-GENERATED by scripts/import-catalog.mjs — do not edit by hand' + NL + 'export const CATALOG_PRODUCTS = ' + JSON.stringify(merged) + NL)
const { CATALOG_CATEGORIES } = await import('file:///' + ROOT + 'src/config/catalog.generated.js')
const cnt = {}; merged.forEach(p => { cnt[p.category] = (cnt[p.category] || 0) + 1 })
write('src/config/catalog.generated.js', '// AUTO-GENERATED by scripts/import-catalog.mjs — do not edit by hand' + NL + 'export const CATALOG_CATEGORIES = ' + JSON.stringify(CATALOG_CATEGORIES.map(c => ({ ...c, count: cnt[c.slug] || 0, description: c.description.replace(/^Shop \d+ /, `Shop ${cnt[c.slug] || 0} `) })), null, 1) + NL + NL)

// per-page config: put the old entries back
const seoOld = JSON.parse(git('src/config/seo.generated.json'))
const seo = JSON.parse(read('src/config/seo.generated.json'))
const faqOld = JSON.parse(git('src/config/faq.generated.json'))
const faq = JSON.parse(read('src/config/faq.generated.json'))
const pcOld = JSON.parse(git('src/config/product-copy.generated.json'))
const pc = JSON.parse(read('src/config/product-copy.generated.json'))
for (const p of restored) {
  const u = urlOf(p)
  seo[u] = seoOld[u]
  if (REAL[p.slug]) seo[u].kw = [REAL[p.slug][0], ...seo[u].kw.filter(k => k !== seo[u].kw[0]).slice(0, 4)]
  if (faqOld.pages[u]) faq.pages[u] = faqOld.pages[u]
  if (pcOld[p.slug]) pc[p.slug] = pcOld[p.slug]
}
write('src/config/seo.generated.json', JSON.stringify(seo))
write('src/config/faq.generated.json', JSON.stringify(faq))
write('src/config/product-copy.generated.json', JSON.stringify(pc))

// redirects: drop the ones for restored URLs
const redirects = JSON.parse(read('src/config/product-redirects.generated.json'))
const keepR = redirects.filter(r => !restored.some(p => r.source === `/shop/${p.category}/${p.slug}`))
console.log('redirects', redirects.length, '->', keepR.length)
write('src/config/product-redirects.generated.json', JSON.stringify(keepR, null, 1) + NL)

// keyword register: back with the old rows; a real Semrush primary replaces the generated one
{
  const oldRows = git('docs/used-keywords.csv').split(NL).filter(l => urls.has(l.split(',')[0]))
  const used = new Set(read('docs/used-keywords.csv').toLowerCase().split(NL).map(l => (l.split(',')[3] || '').trim()))
  const rows = oldRows.map(l => {
    const c = l.split(',')
    const slug = c[0].split('/')[3]
    if (REAL[slug] && c[2] === 'primary') {
      if (used.has(REAL[slug][0])) throw new Error('keyword already used: ' + REAL[slug][0])
      return [c[0], 'product', 'primary', REAL[slug][0], REAL[slug][1], REAL[slug][2], REAL[slug][3], 'semrush-2026-11-06'].join(',')
    }
    return l
  })
  const reg = read('docs/used-keywords.csv').replace(/\s+$/, '')
  write('docs/used-keywords.csv', reg + NL + rows.join(NL) + NL)
  console.log('register rows restored', rows.length)
}
// link plan: rows for the restored pages whose other end still exists
{
  const NLr = NL
  const oldLp = git('docs/link-plan.csv').split(NLr)
  const lpNow = read('docs/link-plan.csv')
  const add = oldLp.slice(1).filter(l => l && [...urls].some(u => l.includes(u)) && !lpNow.includes(l))
  write('docs/link-plan.csv', lpNow.replace(/\s+$/, '') + NLr + add.join(NLr) + NLr)
  console.log('link-plan rows restored', add.length)
}
console.log(APPLY ? 'APPLIED' : 'DRY RUN')
